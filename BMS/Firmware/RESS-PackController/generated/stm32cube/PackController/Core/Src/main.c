void packcontroller_platform_toggle_wdbeat(void)
{
  if ((GPIOE->ODR & GPIO_ODR_OD1) == 0U)
  {
    GPIOE->BSRR = GPIO_BSRR_BS1;
  }
  else
  {
    GPIOE->BSRR = GPIO_BSRR_BR1;
  }
}

void packcontroller_platform_toggle_heartbeat(void)
{
  if ((GPIOE->ODR & GPIO_ODR_OD2) == 0U)
  {
    GPIOE->BSRR = GPIO_BSRR_BS2;
  }
  else
  {
    GPIOE->BSRR = GPIO_BSRR_BR2;
  }
}

void packcontroller_platform_set_error_led(bool enabled)
{
  GPIOE->BSRR = enabled ? GPIO_BSRR_BS4 : GPIO_BSRR_BR4;
}

bool packcontroller_platform_stored_hardfault_valid(void)
{
  return packcontroller_hardfault_record_valid(
      &g_packcontroller_hardfault_record);
}

void packcontroller_platform_emergency_shutdown(void)
{
  GPIOD->BSRR = GPIO_BSRR_BR0 | GPIO_BSRR_BR3 | GPIO_BSRR_BR4;
  GPIOC->BSRR = GPIO_BSRR_BR0;
  GPIOE->BSRR = GPIO_BSRR_BR1 | GPIO_BSRR_BS4;
}

